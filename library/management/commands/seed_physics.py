class Command(BaseCommand):
    help = "Додати два оригінальні демонстраційні зошити з фізики українською"

    def handle(self, *args, **options):
        created_books = 0
        created_guides = 0
        for book_data, examples in WORKBOOKS:
            book, created = StudyBook.objects.get_or_create(
                grade=book_data["grade"],
                title=book_data["title"],
                defaults=book_data,
            )
            created_books += created
            for example in examples:
                _, created = ExerciseGuide.objects.get_or_create(
                    workbook=book,
                    page_number=example["page_number"],
                    exercise_number=example["exercise_number"],
                    defaults=example,
                )
                created_guides += created
        self.stdout.write(
            self.style.SUCCESS(f"Створено зошитів: {created_books}; додано пояснень: {created_guides}.")
        )